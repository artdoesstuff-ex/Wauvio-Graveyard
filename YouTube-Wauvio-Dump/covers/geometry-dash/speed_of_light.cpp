static void mix_mono_at(StereoBuffer& dst, const Buffer& src,
                        double t_sec, float gain, int sr)
{
    const size_t off = (size_t)(t_sec * sr);
    for (size_t i = 0; i < src.size() && off + i < dst.size(); ++i) {
        dst.L[off + i] += src[i] * gain;
        dst.R[off + i] += src[i] * gain;
    }
}

static void mix_stereo_at(StereoBuffer& dst, const StereoBuffer& src,
                          double t_sec, float gain, int sr)
{
    const size_t off = (size_t)(t_sec * sr);
    for (size_t i = 0; i < src.size() && off + i < dst.size(); ++i) {
        dst.L[off + i] += src.L[i] * gain;
        dst.R[off + i] += src.R[i] * gain;
    }
}

static StereoBuffer make_flute(double freq, double dur, int sr)
{
    double d = std::max(0.02, dur);
    Buffer mono = make_buffer(d, sr);

    Oscillator o1(WaveShape::Sine,     freq,       0.72);
    Oscillator o2(WaveShape::Sine,     freq * 2.0, 0.34);
    Oscillator o3(WaveShape::Triangle, freq * 3.0, 0.12);

    NoiseGenerator ng(31u);
    double vib_phase = 0.0;
    for (size_t i = 0; i < mono.size(); ++i) {
        vib_phase += TWO_PI * 5.8 / sr;
        if (vib_phase >= TWO_PI) vib_phase -= TWO_PI;
        double t  = (double)i / sr;
        double ve = std::min(1.0, std::max(0.0, (t - 0.08) / 0.08));
        double vib = std::sin(vib_phase) * freq * (std::pow(2.0, 9.0/1200.0) - 1.0) * ve;
        o1.frequency = freq + vib;
        o2.frequency = freq * 2.0 + vib * 2.0;
        float breath = ng.tick_white() * 0.02f * (float)std::min(1.0, t / 0.05);
        mono[i] = o1.tick(sr) + o2.tick(sr) + o3.tick(sr) + breath;
    }

    HighPassFilter hpf(350.0, sr);
    hpf.process(mono);
    BiquadEQ presence(BiquadEQ::Type::Peak,    4000.0, 3.5, 1.8);
    BiquadEQ air(BiquadEQ::Type::HighShelf,    5500.0, 2.5, 0.7);
    presence.process(mono, sr);
    air.process(mono, sr);

    double rel = std::min(0.06, d * 0.20);
    ADSR env(0.010, d * 0.08, 0.92, rel);
    env.apply(mono, d, std::max(0.0, d - rel), sr);

    return haas_widen(mono, 8.0, sr);
}

static StereoBuffer make_violin(double freq, double dur, int sr)
{
    double d = std::max(0.02, dur);
    Buffer mono = make_buffer(d, sr);

    Oscillator o1(WaveShape::BL_Sawtooth, freq,         0.50);
    Oscillator o2(WaveShape::BL_Sawtooth, freq * 1.005, 0.32);
    Oscillator o3(WaveShape::Sine,        freq * 3.0,   0.10);

    double vib_phase = 0.0;
    const double vib_depth = freq * (std::pow(2.0, 8.0/1200.0) - 1.0);
    for (size_t i = 0; i < mono.size(); ++i) {
        vib_phase += TWO_PI * 5.5 / sr;
        if (vib_phase >= TWO_PI) vib_phase -= TWO_PI;
        double t  = (double)i / sr;
        double ve = std::min(1.0, std::max(0.0, (t - 0.10) / 0.10));
        double vib = std::sin(vib_phase) * vib_depth * ve;
        o1.frequency = freq + vib;
        o2.frequency = freq * 1.005 + vib;
        mono[i] = o1.tick(sr) + o2.tick(sr) + o3.tick(sr);
    }

    BiquadEQ form(BiquadEQ::Type::Peak, 2500.0, 2.0, 2.5);
    form.process(mono, sr);
    SVFilter vln_lp(SVFilter::Mode::LowPass, 3500.0, 0.65);
    vln_lp.process(mono, sr);
    HighPassFilter hpf(180.0, sr);
    hpf.process(mono);

    double atk = std::min(0.06, d * 0.15);
    double rel = std::min(0.25, d * 0.22);
    DAHDSR env(0.0, atk, 0.0, d * 0.08, 0.72, rel);
    env.apply(mono, d, std::max(0.0, d - rel), sr);

    return haas_widen(mono, 12.0, sr);
}

static Buffer make_viola(double freq, double dur, int sr)
{
    double d = std::max(0.02, dur);
    Buffer buf = make_buffer(d, sr);

    Oscillator o1(WaveShape::BL_Sawtooth, freq,       0.52);
    Oscillator o2(WaveShape::BL_Sawtooth, freq * 2.0, 0.24);
    Oscillator o3(WaveShape::Triangle,    freq * 3.0, 0.12);

    double fl = 0.0;
    for (size_t i = 0; i < buf.size(); ++i) {
        fl += TWO_PI * 5.8 / sr;
        if (fl >= TWO_PI) fl -= TWO_PI;
        buf[i] = (o1.tick(sr) + o2.tick(sr) + o3.tick(sr)) * (1.0f + 0.03f * (float)std::sin(fl));
    }

    BiquadEQ nasal(BiquadEQ::Type::Peak,   600.0, 1.5, 2.0);
    SVFilter   lp(SVFilter::Mode::LowPass, 3800.0, 0.65);
    nasal.process(buf, sr);
    lp.process(buf, sr);

    double atk = std::min(0.08, d * 0.18);
    double rel = std::min(0.22, d * 0.22);
    DAHDSR env(0.0, atk, 0.0, d * 0.10, 0.80, rel);
    env.apply(buf, d, std::max(0.0, d - rel), sr);
    return buf;
}

static Buffer make_cello(double freq, double dur, int sr)
{
    double d = std::max(0.02, dur);
    Buffer buf = make_buffer(d, sr);

    Oscillator o1(WaveShape::BL_Sawtooth, freq,       0.50);
    Oscillator o2(WaveShape::BL_Sawtooth, freq * 2.0, 0.22);
    Oscillator o3(WaveShape::Sine,        freq * 0.5, 0.26);

    double fl = 0.0;
    for (size_t i = 0; i < buf.size(); ++i) {
        fl += TWO_PI * 6.0 / sr;
        if (fl >= TWO_PI) fl -= TWO_PI;
        buf[i] = (o1.tick(sr) + o2.tick(sr) + o3.tick(sr)) * (1.0f + 0.04f * (float)std::sin(fl));
    }

    BiquadEQ body(BiquadEQ::Type::Peak,   320.0, 2.0, 1.8);
    SVFilter   lp(SVFilter::Mode::LowPass, 3500.0, 0.65);
    body.process(buf, sr);
    lp.process(buf, sr);

    double atk = std::min(0.10, d * 0.18);
    double rel = std::min(0.38, d * 0.25);
    DAHDSR env(0.0, atk, 0.0, d * 0.12, 0.80, rel);
    env.apply(buf, d, std::max(0.0, d - rel), sr);
    return buf;
}

static Buffer make_contrabass(double freq, double dur, int sr)
{
    double d = std::max(0.02, dur);
    Buffer buf = make_buffer(d, sr);

    Oscillator o1(WaveShape::Sine,        freq,       0.58);
    Oscillator o2(WaveShape::Sine,        freq * 2.0, 0.28);
    Oscillator o3(WaveShape::BL_Sawtooth, freq,       0.16);
    for (auto& s : buf) s = o1.tick(sr) + o2.tick(sr) + o3.tick(sr);

    SVFilter lp(SVFilter::Mode::LowPass, 500.0, 0.60);
    lp.process(buf, sr);

    double atk = std::min(0.12, d * 0.20);
    double rel = std::min(0.50, d * 0.28);
    DAHDSR env(0.0, atk, 0.0, d * 0.10, 0.80, rel);
    env.apply(buf, d, std::max(0.0, d - rel), sr);
    return buf;
}

static void print_help(const char* prog) {
    std::cout
        << "At the Speed of Light - Orchestral Arrangement\n"
        << "Usage:\n  " << prog << " [options]\n\n"
        << "  -o, --output <file>   Output WAV (default: light.wav)\n"
        << "      --play            Play after rendering\n"
        << "  -h, --help            Show help\n";
}

int main(int argc, char** argv)
{
    std::string output  = "light.wav";
    bool        do_play = false;

    for (int i = 1; i < argc; ++i) {
        std::string a = argv[i];
        if (a == "-o" || a == "--output") {
            if (i + 1 < argc) output = argv[++i];
            else { std::cerr << "Missing argument\n"; return 1; }
        } else if (a == "--play") {
            do_play = true;
        } else if (a == "-h" || a == "--help") {
            print_help(argv[0]); return 0;
        } else {
            std::cerr << "Unknown: " << a << "\n"; return 1;
        }
    }

    global_config().sample_rate = SR;
    global_config().channels    = 2;
    global_config().bits        = 16;

    constexpr double TOTAL_DUR = 248.0;
    const size_t total = (size_t)(TOTAL_DUR * SR);

    std::cout << "At the Speed of Light - Orchestral Arrangement\n"
              << "  162 BPM → 122 BPM  |  " << std::fixed << std::setprecision(1)
              << TOTAL_DUR << " s\n\n";

    StereoBuffer master(total, 0.0f);

    std::cout << "  [1/5] Contrabass (" << contrabass_notes_count << " notes)...\n" << std::flush;
    for (int i = 0; i < contrabass_notes_count; ++i) {
        const NoteEvent& n = contrabass_notes[i];
        mix_mono_at(master, make_contrabass(n.freq, n.dur, SR), n.t, 0.65f, SR);
    }

    std::cout << "  [2/5] Cello (" << cello_notes_count << " notes)...\n" << std::flush;
    for (int i = 0; i < cello_notes_count; ++i) {
        const NoteEvent& n = cello_notes[i];
        mix_mono_at(master, make_cello(n.freq, n.dur, SR), n.t, 0.60f, SR);
    }

    std::cout << "  [3/5] Viola (" << viola_notes_count << " notes)...\n" << std::flush;
    for (int i = 0; i < viola_notes_count; ++i) {
        const NoteEvent& n = viola_notes[i];
        mix_mono_at(master, make_viola(n.freq, n.dur, SR), n.t, 0.55f, SR);
    }

    std::cout << "  [4/5] Violin (" << violin_notes_count << " notes)...\n" << std::flush;
    for (int i = 0; i < violin_notes_count; ++i) {
        const NoteEvent& n = violin_notes[i];
        StereoBuffer sb = make_violin(n.freq, n.dur, SR);
        mix_stereo_at(master, sb, n.t, 0.60f, SR);
    }

    std::cout << "  [5/5] Flute (" << flute_notes_count << " notes)...\n" << std::flush;
    for (int i = 0; i < flute_notes_count; ++i) {
        const NoteEvent& n = flute_notes[i];
        StereoBuffer sb = make_flute(n.freq, n.dur, SR);
        mix_stereo_at(master, sb, n.t, 0.90f, SR);
    }

    std::cout << "\n  Master bus...\n" << std::flush;

    Reverb rvL; rvL.room_size = 0.88f; rvL.wet = 0.30f; rvL.dry = 0.92f; rvL.init(SR);
    Reverb rvR; rvR.room_size = 0.90f; rvR.wet = 0.30f; rvR.dry = 0.92f; rvR.init(SR);
    rvL.process(master.L);
    rvR.process(master.R);

    ParametricEQ eq;
    eq.low_shelf  = BiquadEQ(BiquadEQ::Type::LowShelf,  120.0, -2.0, 0.7);
    eq.peak       = BiquadEQ(BiquadEQ::Type::Peak,      3500.0, -1.5, 1.5);
    eq.high_shelf = BiquadEQ(BiquadEQ::Type::HighShelf, 7000.0, -1.5, 0.7);
    eq.process(master, SR);

    distortion::apply_soft_clip(master.L, 1.50f);
    distortion::apply_soft_clip(master.R, 1.50f);

    fade_in(master,  0.25, SR);
    fade_out(master, 3.00, SR);

    normalize(master, 0.92f);
    clamp_buffer(master);

    std::cout << "  Writing: " << output << "\n";
    save_wav_stereo(master, output, SR);
    std::cout << "  Done.\n";

    if (do_play) {
        std::cout << "  Playing (press Enter to stop)...\n";
        PlaybackHandle h = play_async(master, SR);
        std::thread([h]() mutable { std::cin.get(); h.stop(); }).detach();
        h.wait();
        std::cout << "  Playback finished.\n";
    }

    return 0;
}
